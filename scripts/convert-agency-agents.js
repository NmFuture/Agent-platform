function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return { frontmatter: {}, body: content };

  const fm = {};
  match[1].split("\n").forEach((line) => {
    const [key, ...rest] = line.split(":");
    if (key && rest.length > 0) {
      fm[key.trim()] = rest.join(":").trim();
    }
  });
  return { frontmatter: fm, body: content.slice(match[0].length).trim() };
}

function extractSections(body) {
  const sections = {};
  const lines = body.split("\n");
  let currentSection = "general";
  let currentContent = [];

  lines.forEach((line) => {
    const headingMatch = line.match(/^(#{1,3})\s+(.+)/);
    if (headingMatch) {
      if (currentContent.length > 0) {
        sections[currentSection] = currentContent.join("\n").trim();
        currentContent = [];
      }
      currentSection = headingMatch[2]
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
    } else {
      currentContent.push(line);
    }
  });

  if (currentContent.length > 0) {
    sections[currentSection] = currentContent.join("\n").trim();
  }

  return sections;
}

function sanitizeId(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 50);
}

function readAgentFiles(dir) {
  const results = [];

  readdirSync(dir).forEach((item) => {
    const fullPath = join(dir, item);
    const stat = statSync(fullPath);

    if (stat.isDirectory()) {
      results.push(...readAgentFiles(fullPath));
    } else if (item.endsWith(".md") && item.includes("-")) {
      const content = readFileSync(fullPath, "utf-8");
      const relPath = relative(SOURCE_DIR, fullPath);
      const category = relPath.split("/")[0];
      const { frontmatter, body } = parseFrontmatter(content);
      const sections = extractSections(body);

      if (frontmatter.name) {
        results.push({
          id: sanitizeId(frontmatter.name),
          name: frontmatter.name,
          description: frontmatter.description || sections["your-core-mission"]?.split("\n").find(l => l.trim()) || "",
          color: frontmatter.color || "blue",
          emoji: frontmatter.emoji || "🤖",
          vibe: frontmatter.vibe || "",
          category: CATEGORY_MAP[category] || category,
          categoryId: category,
          rolePrompt: body.slice(0, 4000),
          inputs: ["任务说明"],
          outputs: ["执行结果"],
          skills: [],
          runnable: false,
          sourceFile: relPath,
        });
      }
    }
  });

  return results;
}

